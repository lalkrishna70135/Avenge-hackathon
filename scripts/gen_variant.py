"""Generate variant B's prompt section from its one-line diff with Sarvam, for each scenario.

Usage: .venv/bin/python scripts/gen_variant.py [scenarios/win.yaml ...]   (default: all scenarios)

Writes scenarios/variants/<experiment_id>.txt and sets variant_b.prompt_file in the YAML.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from abtest.variants import generate  # noqa: E402

paths = [Path(p) for p in sys.argv[1:]] or sorted((ROOT / "scenarios").glob("*.yaml"))
out_dir = ROOT / "scenarios" / "variants"
out_dir.mkdir(exist_ok=True)

for path in paths:
    cfg = yaml.safe_load(path.read_text())
    base = (ROOT / cfg["base_prompt_file"]).read_text()
    diff = cfg["variant_b"]["diff"]
    res = generate(base, diff, cfg["variant_b"].get("anchor"), cfg["variant_b"].get("window"))
    out = out_dir / f"{cfg['experiment_id']}.txt"
    lo, hi = res["lines"]
    out.write_text(
        f"# Variant B for {cfg['experiment_id']}, generated by {res['model']}\n"
        f"# Replaces lines {lo}-{hi} of {cfg['base_prompt_file']}\n"
        f"# Diff: {diff}\n\n"
        f"{res['rewritten']}\n"
    )
    # set prompt_file without rewriting the rest of the YAML
    text = path.read_text()
    rel = out.relative_to(ROOT).as_posix()
    if "\n  prompt_file:" not in text:
        text = text.replace(f"  diff: ", f"  prompt_file: {rel}\n  diff: ", 1)
        path.write_text(text)
    print(f"{path.name}: lines {lo}-{hi} -> {rel} ({len(res['rewritten'])} chars)")
