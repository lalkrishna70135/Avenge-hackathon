"""Stage 5: turn the simulated pilot into a 4th engine scenario, scenarios/pilot.yaml.

Usage: .venv/bin/python scripts/pilot_to_scenario.py [--experiment exp-win]   (default: exp-win, the change we
would ship; pass another experiment id, or "largest" for the largest pilot lift)
The pilot's lead effect is carried over as an odds ratio to the real connected-call lead rate (clamped to
what the simulator can realise, as a safeguard); its duration ratio becomes duration_mult. Then run
scripts/run_scenarios.py to route, test, decide and roll it out like the other scenarios.
"""
import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from abtest import convo  # noqa: E402
from abtest.loader import load  # noqa: E402
from abtest.pilot import to_true_effect  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--experiment", default="exp-win")
args = ap.parse_args()

summary = {k: v for k, v in json.loads((convo.PILOT_DIR / "summary.json").read_text()).items()
           if v and k != convo.AA_ID}          # the A/A check is a noise yardstick, never a candidate change
exp_id = max(summary, key=lambda k: summary[k]["lift_pp"]) if args.experiment == "largest" else args.experiment
s = summary[exp_id]
src = yaml.safe_load((ROOT / "scenarios" / f"{exp_id.removeprefix('exp-')}.yaml").read_text())
p_c = load().card()["success_rate_connected"]
eff = to_true_effect(s, p_c)
vb = {k: v for k, v in src["variant_b"].items() if k != "prompt_sha256"}
out = {
    "experiment_id": "exp-pilot",
    "title": f"Pilot-driven: {src['variant_b']['name'].removeprefix('B: ')}",
    "salt": "exp-pilot-5d0e",
    "share_b": 0.10,
    "mde_pp": src.get("mde_pp", 0.03),
    "base_prompt_file": src["base_prompt_file"],
    "variant_a": src.get("variant_a", {"name": "A (control)"}),
    "variant_b": vb,
    "true_effect": {"success_pp": eff["success_pp"], "duration_mult": eff["duration_mult"]},
    "seed": 22,          # illustrative run; the Error rates tab gives the decision rates over 1,000 reruns
    "pilot_of": exp_id,
    "pilot_evidence": {"pairs": s["pairs"], "sim_lead_rate_a": round(s["A"]["lead_rate"], 4),
                       "sim_lead_rate_b": round(s["B"]["lead_rate"], 4), "lift_pp": round(s["lift_pp"], 4),
                       "lift_ci": [round(x, 4) for x in s["lift_ci"]], "p_value": round(s["p_value"], 4),
                       "duration_ratio": round(s["duration_ratio"], 4), **eff},
}
path = ROOT / "scenarios" / "pilot.yaml"
path.write_text("# Generated by scripts/pilot_to_scenario.py from runs/pilot/summary.json. Do not edit by hand.\n"
                + yaml.safe_dump(out, sort_keys=False, allow_unicode=True))
print(f"{path.relative_to(ROOT)} from {exp_id}: simulated lead rate {s['A']['lead_rate']:.0%} -> {s['B']['lead_rate']:.0%} "
      f"(odds ratio {eff['odds_ratio']:.2f}) -> true effect {100 * eff['success_pp']:+.1f} pp on the real "
      f"{p_c:.0%} connected lead rate{' (clamped)' if eff['clamped'] else ''}, duration x{eff['duration_mult']}")
